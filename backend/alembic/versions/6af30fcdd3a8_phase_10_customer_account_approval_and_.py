#: SQLite gained ``ALTER TABLE ... DROP COLUMN`` in 3.35.0 (March 2021). The verified
#: environment runs 3.49.1 (``docs/DEPLOYMENT.md`` section 9).
_SQLITE_DROP_COLUMN_MINIMUM = (3, 35, 0)


def _refuse_old_sqlite(bind: sa.engine.Connection) -> None:
    """Fail loudly rather than silently corrupting ``customers`` on an old SQLite.

    This matters because the alternative is worse than an error. Alembic's batch mode
    implements ``DROP COLUMN`` by rebuilding the table: create a copy, move the rows, drop
    the original, rename. On this database that rebuild **cannot succeed** -- eleven tables
    hold foreign keys into ``customers``, ``PRAGMA foreign_keys`` is ON for every
    connection (``app/core/db.py``), and dropping the original violates every one of them.
    The first attempt at this downgrade failed exactly that way, which is what a tested
    downgrade is for.

    Turning the pragma off around the rebuild is the usual workaround and is not available
    here: ``PRAGMA foreign_keys`` is a no-op inside a transaction, and Alembic runs a
    migration inside one. So this downgrade uses the **native** statement, which rebuilds
    nothing, touches no other table and cannot violate a foreign key -- and refuses to run
    where that statement does not exist, rather than falling back to the rebuild that is
    known not to work.
    """
    if bind.dialect.name != "sqlite":
        return
    version = bind.dialect.server_version_info or (0, 0, 0)
    if tuple(version[:3]) < _SQLITE_DROP_COLUMN_MINIMUM:
        raise RuntimeError(
            "Downgrading 6af30fcdd3a8 needs SQLite 3.35.0 or newer for native "
            f"ALTER TABLE ... DROP COLUMN; this build reports "
            f"{'.'.join(str(part) for part in version)}. Restore from a backup instead."
        )


