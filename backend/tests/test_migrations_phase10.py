def test_the_attempt_table_claims_by_a_unique_digest(tmp_path):
    """The claim is a unique index, which is how SQLite serializes without a row lock."""
    path = tmp_path / "attempts.db"
    assert _alembic(f"sqlite:///{path.as_posix()}", "upgrade", "head").returncode == 0

    columns = set(_columns(path, "customer_account_approval_attempts"))
    assert "idempotency_key_digest" in columns
    assert "request_fingerprint" in columns
    # No raw key, no payload, no address.
    assert "idempotency_key" not in columns
    assert not any("email" in column or "address" in column for column in columns)

    # Declared as a table-level UNIQUE constraint, which SQLite backs with an auto-index
    # rather than a named one. The constraint is what enforces the claim, so it is read
    # out of the table's DDL by name -- and then actually exercised, because a name in a
    # schema is not the same as a refusal at write time.
    connection = sqlite3.connect(path)
    try:
        ddl = connection.execute(
            "select sql from sqlite_master where name = ?",
            ("customer_account_approval_attempts",),
        ).fetchone()[0]
        unique_indexes = [
            row[1]
            for row in connection.execute("pragma index_list(customer_account_approval_attempts)")
            if row[2] == 1
        ]
    finally:
        connection.close()
    assert "uq_ca_approval_attempts_idempotency_key_digest" in ddl
    assert len(unique_indexes) == 1

    connection = _connect(path)
    refused = False
    try:
        for _ in range(2):
            connection.execute(
                """
                insert into customer_account_approval_attempts (
                    idempotency_key_digest, identity_id, action, request_fingerprint,
                    outcome, created_at
                ) values ('same-digest', 1, 'create_new', 'fp', 'approved_created',
                          '2026-03-01 09:00:00')
                """
            )
    except sqlite3.IntegrityError:
        refused = True
    finally:
        connection.close()
    assert refused, "the unique claim did not refuse a second insert"


def test_both_new_tables_declare_deletion_behaviour_on_every_foreign_key(tmp_path):
    path = tmp_path / "fks.db"
    assert _alembic(f"sqlite:///{path.as_posix()}", "upgrade", "head").returncode == 0

    for table in PHASE_10_TABLES:
        keys = _foreign_keys(path, table)
        assert keys
        for _column, _target, _to, on_delete in keys:
            assert on_delete in {"CASCADE", "SET NULL"}, (table, on_delete)


# --- From a populated Phase 9 database ----------------------------------------


def test_upgrading_a_populated_phase_9_database_loses_no_row(tmp_path):
    path, url = _phase_9_database(tmp_path, "populated.db")
    before = _row_counts(path)
    assert _alembic(url, "upgrade", PHASE_10_REVISION).returncode == 0
    after = _row_counts(path)

    for table, count in before.items():
        assert after[table] == count, table
    assert set(after) - set(before) == PHASE_10_TABLES


def test_every_customer_and_address_value_survives_the_upgrade(tmp_path):
    """Value by value, with the two new columns excluded from the comparison."""
    path, url = _phase_9_database(tmp_path, "values.db")
    customers_before = _rows(path, "customers")
    addresses_before = _rows(path, "customer_addresses")

    assert _alembic(url, "upgrade", PHASE_10_REVISION).returncode == 0

    assert _rows(path, "customers", exclude=PHASE_10_CUSTOMER_COLUMNS) == customers_before
    assert _rows(path, "customer_addresses") == addresses_before
    # And the new columns are null on every pre-existing row.
    connection = sqlite3.connect(path)
    try:
        values = list(connection.execute("select legal_name, display_name from customers"))
    finally:
        connection.close()
    assert values == [(None, None), (None, None)]


def test_the_nine_phase_9_tables_are_untouched(tmp_path):
    path, url = _phase_9_database(tmp_path, "phase9.db")
    before = {table: _schema_fingerprint(path)[table] for table in PHASE_9_TABLES}
    assert _alembic(url, "upgrade", "head").returncode == 0
    after = {table: _schema_fingerprint(path)[table] for table in PHASE_9_TABLES}
    assert after == before


def test_role_merge_provenance_survives_the_whole_round_trip(tmp_path):
    """Owned by ``a1c7f4d92b30``, and no business of this migration (DEC-0089)."""
    path, url = _phase_9_database(tmp_path, "provenance.db")

    def snapshot():
        connection = sqlite3.connect(path)
        try:
            return (
                [row[1] for row in connection.execute("pragma table_info(role_merge_provenance)")],
                list(connection.execute("select * from role_merge_provenance")),
            )
        finally:
            connection.close()

    before = snapshot()
    assert _alembic(url, "upgrade", "head").returncode == 0
    assert snapshot() == before
    assert _alembic(url, "downgrade", "-1").returncode == 0
    assert snapshot() == before
    assert _alembic(url, "upgrade", "head").returncode == 0
    assert snapshot() == before

    source = (
        BACKEND_ROOT
        / "alembic"
        / "versions"
        / "6af30fcdd3a8_phase_10_customer_account_approval_and_.py"
    ).read_text(encoding="utf-8")
    # Mentioned in the docstring, as a statement of what it does not do; never in code.
    body = source.split('"""', 2)[2]
    assert "role_merge_provenance" not in body


