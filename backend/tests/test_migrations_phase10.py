def test_the_downgrade_removes_exactly_the_two_tables_and_the_two_columns(tmp_path):
    path, url = _phase_9_database(tmp_path, "down.db")
    assert _alembic(url, "upgrade", PHASE_10_REVISION).returncode == 0
    assert _tables(path) >= PHASE_10_TABLES

    result = _alembic(url, "downgrade", PHASE_9_REVISION)
    assert result.returncode == 0, result.stderr

    assert not (PHASE_10_TABLES & _tables(path))
    assert not (PHASE_10_CUSTOMER_COLUMNS & set(_columns(path, "customers")))
    assert _tables(path) >= PHASE_9_TABLES


def test_the_downgrade_survives_the_foreign_keys_into_customers(tmp_path):
    """The regression this migration was rewritten for.

    ``customers`` has children in eleven tables and the fixture populates several of
    them. The batch rebuild the autogenerated downgrade used failed here with a foreign
    key violation; the native ``DROP COLUMN`` does not rebuild and does not.
    """
    path, url = _phase_9_database(tmp_path, "fkdown.db")
    assert _alembic(url, "upgrade", "head").returncode == 0

    connection = _connect(path)
    try:
        children = connection.execute("select count(*) from customer_addresses").fetchone()[0]
        shipments = connection.execute("select count(*) from shipments").fetchone()[0]
    finally:
        connection.close()
    assert children and shipments

    result = _alembic(url, "downgrade", "-1")
    assert result.returncode == 0, result.stderr
    assert "FOREIGN KEY" not in result.stderr
    assert "_alembic_tmp_customers" not in _tables(path)


def test_downgrade_then_reupgrade_restores_the_schema_exactly(tmp_path):
    path, url = _phase_9_database(tmp_path, "roundtrip.db")
    assert _alembic(url, "upgrade", "head").returncode == 0
    upgraded = _schema_fingerprint(path)

    assert _alembic(url, "downgrade", "-1").returncode == 0
    assert _alembic(url, "upgrade", "head").returncode == 0

    assert _schema_fingerprint(path) == upgraded


def test_existing_data_survives_downgrade_and_reupgrade(tmp_path):
    """The claim the migration's docstring makes, asserted value by value.

    Two customers with children, an address, a shipment, a consent event, an alias, an
    identity and a proposal -- all of it compared before and after, with the two dropped
    columns excluded because dropping them is the point of a downgrade.
    """
    path, url = _phase_9_database(tmp_path, "survive.db")
    snapshot = {
        table: _rows(path, table)
        for table in (
            "customers",
            "customer_addresses",
            "shipments",
            "consent_events",
            "customer_id_aliases",
            "customer_identities",
            "customer_data_proposals",
            "customer_data_proposal_fields",
            "users",
        )
    }

    assert _alembic(url, "upgrade", PHASE_10_REVISION).returncode == 0
    assert _alembic(url, "downgrade", PHASE_9_REVISION).returncode == 0

    for table, rows in snapshot.items():
        assert _rows(path, table) == rows, table

    assert _alembic(url, "upgrade", PHASE_10_REVISION).returncode == 0
    for table, rows in snapshot.items():
        exclude = PHASE_10_CUSTOMER_COLUMNS if table == "customers" else frozenset()
        assert _rows(path, table, exclude=exclude) == rows, table


