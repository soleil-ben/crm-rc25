def _alembic(database_url: str, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "alembic", *args],
        cwd=BACKEND_ROOT,
        env={
            "PATH": "",
            "SYSTEMROOT": "C:\\Windows",
            "DATABASE_URL": database_url,
            "SECRET_KEY": "test-only-secret",
            "ENVIRONMENT": "test",
        },
        capture_output=True,
        text=True,
    )


def _connect(path: Path) -> sqlite3.Connection:
    connection = sqlite3.connect(path)
    connection.execute("pragma foreign_keys=on")
    return connection


def _tables(path: Path) -> set[str]:
    connection = sqlite3.connect(path)
    try:
        return {
            row[0]
            for row in connection.execute("select name from sqlite_master where type='table'")
        }
    finally:
        connection.close()


def _columns(path: Path, table: str) -> list[str]:
    connection = sqlite3.connect(path)
    try:
        return [row[1] for row in connection.execute(f"pragma table_info({table})")]
    finally:
        connection.close()


def _indexes(path: Path, table: str) -> set[str]:
    connection = sqlite3.connect(path)
    try:
        return {row[1] for row in connection.execute(f"pragma index_list({table})")}
    finally:
        connection.close()


def _foreign_keys(path: Path, table: str) -> set[tuple[str, str, str, str]]:
    connection = sqlite3.connect(path)
    try:
        return {
            (row[3], row[2], row[4], row[6])
            for row in connection.execute(f"pragma foreign_key_list({table})")
        }
    finally:
        connection.close()


def _schema_fingerprint(path: Path) -> dict[str, tuple[frozenset[str], frozenset[str]]]:
    return {
        table: (frozenset(_columns(path, table)), frozenset(_indexes(path, table)))
        for table in sorted(_tables(path))
        if not table.startswith("sqlite_")
    }


def _row_counts(path: Path) -> dict[str, int]:
    connection = sqlite3.connect(path)
    try:
        return {
            table: connection.execute(f"select count(*) from {table}").fetchone()[0]
            for table in sorted(_tables(path))
            if not table.startswith("sqlite_") and table != "alembic_version"
        }
    finally:
        connection.close()


def _rows(path: Path, table: str, *, exclude: set[str] = frozenset()) -> list[tuple]:
    """Every row of a table, column by column, with the named columns left out.

    Value-level rather than a count, because a count cannot detect a rebuild that
    preserved the number of rows and lost or reordered their contents -- which is exactly
    the failure mode a batch table rebuild has.
    """
    columns = [name for name in _columns(path, table) if name not in exclude]
    connection = sqlite3.connect(path)
    try:
        selected = ", ".join(columns)
        return list(connection.execute(f"select {selected} from {table} order by id"))
    finally:
        connection.close()


